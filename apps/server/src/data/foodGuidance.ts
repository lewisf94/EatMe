export const FALLBACK_GUIDANCE: FoodGuidanceRule = {
  id: "other_food",
  keywords: [],
  categoryKey: "other_food",
  locationKey: "cupboard",
  unopenedDays: null,
  confidence: "low",
  sourceIds: [],
  note: "No reliable local match; check the pack for its storage instruction and date.",
};

const normalize = (value: string): string =>
  value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();

export function matchFoodGuidanceRule(
  name: string,
  categoryHints: string[] = [],
  preferredRuleId?: string | null,
): FoodGuidanceRule {
  if (preferredRuleId) {
    const saved = FOOD_GUIDANCE_RULES.find((rule) => rule.id === preferredRuleId);
    if (saved) return saved;
  }

  const haystack = normalize([name, ...categoryHints].join(" "));
  if (!haystack) return FALLBACK_GUIDANCE;
  for (const rule of FOOD_GUIDANCE_RULES) {
    if (rule.exclude?.some((term) => haystack.includes(normalize(term)))) continue;
    if (rule.keywords.some((term) => haystack.includes(normalize(term)))) return rule;
  }
  return FALLBACK_GUIDANCE;
}
